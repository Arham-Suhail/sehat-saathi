"""Generate a VAPID key pair for Web Push and append it to backend/.env.

    cd backend && .venv/Scripts/python -m scripts.gen_vapid https://<your-web-app>

The PRIVATE key is written only to .env (gitignored) and is never printed. Copy the three
VAPID_* lines from .env into the Render dashboard (Environment). Refuses to overwrite keys.
"""

import base64
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

ENV = Path(__file__).resolve().parents[1] / ".env"


def b64u(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def main() -> None:
    subject = sys.argv[1] if len(sys.argv) > 1 else ""
    if not subject.startswith(("https://", "mailto:")):
        sys.exit("usage: python -m scripts.gen_vapid https://<your-web-app>   (or mailto:<ops address>)")
    existing = ENV.read_text(encoding="utf-8") if ENV.exists() else ""
    if "VAPID_PRIVATE_KEY=" in existing:
        sys.exit(".env already has VAPID keys; not overwriting (rotating keys breaks every subscription).")
    key = ec.generate_private_key(ec.SECP256R1())
    private = b64u(key.private_numbers().private_value.to_bytes(32, "big"))
    point = serialization.PublicFormat.UncompressedPoint
    public = b64u(key.public_key().public_bytes(serialization.Encoding.X962, point))
    with ENV.open("a", encoding="utf-8") as f:
        f.write(
            f"\n# Web Push (generated by scripts/gen_vapid.py)\n"
            f"VAPID_PUBLIC_KEY={public}\nVAPID_PRIVATE_KEY={private}\nVAPID_SUBJECT={subject}\n"
        )
    print(f"VAPID keys written to {ENV}")
    print(f"Public key (safe to share): {public}")
    print("Private key: written to .env only. Add all three VAPID_* lines to Render > Environment.")


if __name__ == "__main__":
    main()
